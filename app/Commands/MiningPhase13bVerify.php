<?php

declare(strict_types=1);

namespace App\Commands;

use App\Libraries\CliArgs;
use App\Services\Phase13BVerificationService;
use CodeIgniter\CLI\BaseCommand;
use CodeIgniter\CLI\CLI;
use Throwable;

/**
 * Phase 13B — isolated verification of as-of mining ownership, precision, batching, scheduler reliability and CLI safety.
 * Writes only to coin_platform_phase13b (marker-guarded, dedicated MySQL account). Live DB: SELECT-only fingerprint.
 */
class MiningPhase13bVerify extends BaseCommand
{
    protected $group       = 'Mining';
    protected $name        = 'mining:phase13b-verify';
    protected $description = 'Isolated Phase 13B verification (coin_platform_phase13b only; live DB read-only fingerprint).';
    protected $usage       = 'mining:phase13b-verify [--perf] [--perf-sizes 100,2000,2001,5000,10000] [--skip-batch-compare]';
    protected $options     = [
        '--perf'               => 'Also run the performance harness (long: seeds up to 10000 synthetic members)',
        '--perf-sizes'         => 'Comma-separated member counts for the harness (default 100,2000,2001,5000,10000)',
        '--skip-batch-compare' => 'Skip the 100/250/500/1000 batch-size comparison',
    ];

    public function run(array $params)
    {
        $opt = CliArgs::guard($this->name, [
            'values' => ['perf-sizes' => '/^\d+(,\d+)*$/'],
            'flags'  => ['perf', 'skip-batch-compare'],
        ]);
        if ($opt === null) {
            return 2;
        }

        CLI::write('=== Phase 13B isolated verification ===', 'yellow');
        CLI::write('Target DB: coin_platform_phase13b (marker-guarded). Live coin_platform: SELECT-only fingerprint.');

        $sizes = isset($opt['perf-sizes']) ? array_map('intval', explode(',', (string) $opt['perf-sizes'])) : [100, 2000, 2001, 5000, 10000];

        try {
            $report = (new Phase13BVerificationService())->run([
                'perf' => isset($opt['perf']), 'perf_sizes' => $sizes, 'skip_perf_batch_compare' => isset($opt['skip-batch-compare']),
            ]);
        } catch (Throwable $e) {
            CLI::error($e->getMessage());

            return EXIT_ERROR;
        }

        $json = WRITEPATH . 'phase13b-mining-validation-results.json';
        file_put_contents($json, json_encode($report, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
        $this->writeMarkdown($report);

        foreach ($report['checks'] as $c) {
            CLI::write(($c['ok'] ? '[PASS] ' : '[FAIL] ') . $c['name'] . ' — ' . $c['detail'], $c['ok'] ? 'green' : 'red');
        }
        foreach ($report['errors'] as $e) {
            CLI::error($e['class'] . ': ' . $e['message'] . ' @ ' . $e['file'] . ':' . $e['line']);
        }
        CLI::write('passed=' . $report['passed'] . ' failed=' . $report['failed']);
        CLI::write('JSON: ' . $json);
        CLI::write('Markdown: docs/phase13b-validation-results.md');

        return $report['success'] ? EXIT_SUCCESS : EXIT_ERROR;
    }

    /** @param array<string, mixed> $r */
    private function writeMarkdown(array $r): void
    {
        $esc = static fn (mixed $v): string => str_replace(['|', "\n", "\r"], ['/', ' ', ' '], (string) $v);
        $L   = [];
        $L[] = '# Phase 13B — generated validation results';
        $L[] = '';
        $L[] = 'Generated: ' . ($r['finished_at'] ?? date('c')) . ' — isolated DB `' . ($r['database'] ?? '') . '` — **' . (! empty($r['success']) ? 'ALL CHECKS PASS' : 'FAILURES PRESENT') . '** (' . ($r['passed'] ?? 0) . ' passed / ' . ($r['failed'] ?? 0) . ' failed)';
        $L[] = '';
        $L[] = 'This file is machine-generated by `php spark mining:phase13b-verify`. Narrative: `phase13b-mining-accuracy-report.md`.';
        $L[] = '';
        $L[] = '## 1. Safety / isolation';
        $L[] = '';
        $L[] = '- Isolated database: ' . json_encode($r['provision'] ?? []);
        $L[] = '- Live identity: ' . json_encode($r['live_identity'] ?? []);
        $L[] = '- Kill-switches before: `' . json_encode($r['switches_before'] ?? []) . '`';
        $L[] = '- Kill-switches after: `' . json_encode($r['switches_after'] ?? []) . '`';
        $L[] = '- Live fingerprint BEFORE: `' . json_encode($r['live_fingerprint_before'] ?? null) . '`';
        $L[] = '- Live fingerprint AFTER: `' . json_encode($r['live_fingerprint_after'] ?? null) . '`';
        $L[] = '';
        $L[] = '## 2. Cohort';
        $L[] = '';
        $L[] = '| Case | Member ID | Story |';
        $L[] = '|---|---|---|';
        foreach ($r['cohort'] ?? [] as $c) {
            $L[] = '| ' . $c['case'] . ' | ' . $c['member_id'] . ' | ' . $esc($c['story']) . ' |';
        }
        $L[] = '';
        $L[] = '## 3. Historical as-of ownership cases (policy `T-CALENDAR-HALFUP`: full-day, calendar divisor, HALF_UP)';
        $L[] = '';
        $L[] = 'Posting order: ' . implode(' then ', $r['cases']['run_order'] ?? []) . ' (later date first, so back-dated runs are proven not to see later transactions).';
        $L[] = '';
        $L[] = '| Case | Member ID | Business date | Eligible (expected) | Eligible (recorded) | Rate % | Divisor | Expected income | Actual income | Wallet (exp / act) | Ledger ref | Result |';
        $L[] = '|---|---|---|---:|---:|---:|---:|---:|---:|---|---|---|';
        foreach ($r['cases']['rows'] ?? [] as $x) {
            $L[] = '| ' . implode(' | ', [
                $x['case'], $x['member_id'], $x['business_date'], $x['eligible_expected'], $x['eligible_recorded'] ?? 'n/a', $x['monthly_rate_percent'], $x['divisor'],
                $x['expected_daily_income'], $x['actual_daily_income'], $x['wallet_balance_expected'] . ' / ' . $x['wallet_balance_actual'], $x['ledger_ref'] ?? '—',
                $x['result'] . ($x['wallet_result'] === 'FAIL' ? ' (wallet FAIL)' : ''),
            ]) . ' |';
        }
        $L[] = '';
        $L[] = '## 4. Policy fixture previews (read-only; no production policy selected)';
        $L[] = '';
        $L[] = '| Policy | Case | Date | Cutoff (UTC) | Expected | Actual | Owned | Locked | Reserved | Result |';
        $L[] = '|---|---|---|---|---:|---:|---:|---:|---:|---|';
        foreach ($r['policy_previews']['rows'] ?? [] as $x) {
            $L[] = '| ' . implode(' | ', [$x['policy'], $x['case'], $x['business_date'], $x['cutoff_utc'], $x['eligible_expected'], $x['eligible_actual'], $x['owned'], $x['locked'], $x['reserved'], $x['result']]) . ' |';
        }
        $L[] = '';
        $L[] = '## 5. Timezone';
        $L[] = '';
        $L[] = '```json';
        $L[] = json_encode($r['timezone'] ?? [], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
        $L[] = '```';
        $L[] = '';
        $L[] = '## 6. Precision matrix (engine vs independent integer arithmetic)';
        $L[] = '';
        $L[] = '| Case | Eligible | Rate % | Date | Divisor mode | Divisor | Rounding | Engine | Independent | Result |';
        $L[] = '|---|---:|---:|---|---|---:|---|---:|---:|---|';
        foreach ($r['precision']['rows'] ?? [] as $x) {
            $L[] = '| ' . implode(' | ', [$x['case'], $x['eligible'], $x['rate_percent'], $x['date'], $x['divisor_mode'], $x['divisor'], $x['rounding'], $x['engine'], $x['independent'], $x['result']]) . ' |';
        }
        $L[] = '';
        $L[] = '### Comparative previews (not approvals)';
        $L[] = '';
        $L[] = '| Divisor | Rounding | /1000 coins, 31-day | /1000 coins, 30-day | /1000 coins, 28-day | Cohort total 15 Oct |';
        $L[] = '|---|---|---:|---:|---:|---:|';
        foreach ($r['precision']['comparative_previews'] ?? [] as $x) {
            $L[] = '| ' . implode(' | ', [$x['divisor_mode'], $x['rounding'], $x['per_1000_coins_31_day_month'], $x['per_1000_coins_30_day_month'], $x['per_1000_coins_28_day_month'], $x['cohort_total_15_oct']]) . ' |';
        }
        $L[] = '';
        $L[] = '- Month total per 1000 coins (31 days, HALF_UP): `' . json_encode($r['precision']['month_total_per_1000_coins_oct_31_days'] ?? []) . '` — ' . ($r['precision']['month_total_note'] ?? '');
        $L[] = '';
        $L[] = '## 7. Scheduler simulations (real `php spark mining:post` child processes)';
        $L[] = '';
        $L[] = '| Scenario | Expected | Exit | Scheduler status | Credited now | Duplicates | State | Result | Note |';
        $L[] = '|---|---|---:|---|---:|---:|---|---|---|';
        foreach ($r['scheduler']['scenarios'] ?? [] as $x) {
            $L[] = '| ' . implode(' | ', [$x['scenario'], $esc($x['expected']), $x['exit'], $x['scheduler_status'], $x['credited'] ?? '', $x['duplicates'] ?? '', $x['state'] ?? '', $x['result'], $esc($x['note'])]) . ' |';
        }
        $L[] = '';
        $L[] = '## 8. Case K — missing historical evidence';
        $L[] = '';
        $L[] = '```json';
        $L[] = json_encode($r['case_k'] ?? [], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
        $L[] = '```';
        $L[] = '';
        $L[] = '## 9. CLI syntax audit';
        $L[] = '';
        $L[] = '| Command | Unknown option exit | `--opt=value` exit | Missing value exit | Result |';
        $L[] = '|---|---:|---:|---:|---|';
        foreach ($r['cli_audit']['commands'] ?? [] as $x) {
            $L[] = '| `' . $x['command'] . '` | ' . $x['unknown_option_exit'] . ' | ' . ($x['equals_syntax_exit'] ?? '—') . ' | ' . ($x['missing_value_exit'] ?? '—') . ' | ' . $x['result'] . ' |';
        }
        $L[] = '';
        $L[] = '| Parser case | Args | Result |';
        $L[] = '|---|---|---|';
        foreach ($r['cli_audit']['parser_matrix'] ?? [] as $x) {
            $L[] = '| ' . $x['case'] . ' | `' . $x['args'] . '` | ' . $x['result'] . ' |';
        }
        $L[] = '';
        if (isset($r['performance'])) {
            $p = $r['performance'];
            $L[] = '## 10. Performance (measured, local machine, synthetic data)';
            $L[] = '';
            $L[] = '| Members | Batch | Exit | Wall s | Peak MB | Queries | Batches | Avg batch ms | Credited | Repeat run credited | Ledger rows | Dup groups | Result |';
            $L[] = '|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|';
            foreach ($p['sizes'] ?? [] as $n => $x) {
                $f = $x['first_run'];
                $L[] = '| ' . implode(' | ', [$n, $x['batch_size'], $f['exit'], $f['wall_seconds'], $f['peak_memory_mb'], $f['queries'], $f['batches'], $f['avg_batch_ms'], $f['credited'], $x['repeat_run']['credited'], $x['ledger_rows'], $x['duplicate_groups'], $x['result']]) . ' |';
            }
            $L[] = '';
            $L[] = '### Batch-size comparison (2000 members)';
            $L[] = '';
            $L[] = '| Batch | Exit | Wall s | Peak MB | Queries | Batches | Avg batch ms |';
            $L[] = '|---:|---:|---:|---:|---:|---:|---:|';
            foreach ($p['batch_size_comparison'] ?? [] as $b => $x) {
                $L[] = '| ' . implode(' | ', [$b, $x['exit'], $x['wall_seconds'], $x['peak_memory_mb'], $x['queries'], $x['batches'], $x['avg_batch_ms']]) . ' |';
            }
            $L[] = '';
            $L[] = '### Interrupt + resume (5000 members)';
            $L[] = '';
            $L[] = '```json';
            $L[] = json_encode($p['resume'] ?? [], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
            $L[] = '```';
            $L[] = '';
        }
        $L[] = '## 11. All checks';
        $L[] = '';
        $L[] = '| Result | Check | Detail |';
        $L[] = '|---|---|---|';
        foreach ($r['checks'] ?? [] as $c) {
            $L[] = '| ' . ($c['ok'] ? 'PASS' : '**FAIL**') . ' | `' . $c['name'] . '` | ' . $esc($c['detail']) . ' |';
        }
        foreach ($r['errors'] ?? [] as $e) {
            $L[] = '';
            $L[] = '**Error** `' . $e['class'] . '`: ' . $esc($e['message']) . ' (' . $e['file'] . ':' . $e['line'] . ')';
        }
        $L[] = '';

        file_put_contents(ROOTPATH . 'docs' . DIRECTORY_SEPARATOR . 'phase13b-validation-results.md', implode("\n", $L));
    }
}
