<script>
(function () {
    const select = document.querySelector('[data-lock-plan]');
    const hint = document.querySelector('[data-plan-hint]');
    const unlock = document.querySelector('[data-unlock-date]');
    if (!select || !unlock) return;

    function refresh() {
        const opt = select.options[select.selectedIndex];
        if (!opt || !opt.value) {
            unlock.textContent = '—';
            if (hint) hint.textContent = 'Choose a plan to see duration and limits.';
            return;
        }
        const days = parseInt(opt.getAttribute('data-days') || '0', 10);
        const min = opt.getAttribute('data-min') || '';
        const max = opt.getAttribute('data-max') || '';
        const d = new Date();
        d.setDate(d.getDate() + days);
        unlock.textContent = d.toISOString().slice(0, 10) + ' (approx, server confirms on submit)';
        if (hint) {
            hint.textContent = 'Min ' + min + (max ? ' · Max ' + max : '') + ' · ' + days + ' days · Early unlock off by default';
        }
    }
    select.addEventListener('change', refresh);
    refresh();
})();
</script>
